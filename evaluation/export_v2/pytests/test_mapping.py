def test_epoch_matches_forshor_sites_hash_of_the_same_model():
    assert canon.epoch_of(GOLDEN["model"]) == GOLDEN["epoch"] == "c64165fdd0b538d6"


def test_canonical_json_is_sorted_compact_and_rejects_nan():
    assert canon.canonical_json({"b": 1, "a": [2, {"d": 1, "c": 2}]}) == '{"a":[2,{"c":2,"d":1}],"b":1}'
    try:
        canon.canonical_json({"x": float("nan")})
    except ValueError:
        pass
    else:
        raise AssertionError("NaN must not be hashable")


#: The full run's qubit text as forshor-site's builder wrote it into golden.json BEFORE swap 002 (it said "32 w Toffoli" and ForShor 8e37ce7).
#: golden.json is generated by forshor-site's `scripts/fixture-v2.ts` (not by this repo), which has not been re-run: until it is, those two
#: strings are the only thing the golden test may not compare. When golden.json carries the current text (`mapping.PEAK_LABEL` /
#: `mapping.PEAK_RULE`) the exemption switches itself off and they are compared like everything else.
STALE_GOLDEN_TEXT = ("qubitsLabel", "qubitsRule")


def _golden_text_is_stale(expected):
    run = expected["fullRun"]
    return bool(run) and (run["qubitsLabel"], run["qubitsRule"]) != (mapping.PEAK_LABEL, mapping.PEAK_RULE)


def test_every_panel_equals_what_forshor_sites_builder_made_from_the_same_engine_view():
    for name, case in GOLDEN["cases"].items():
        expected = copy.deepcopy(case["panel"])
        got = mapping.panel_of(case["view"], epoch=GOLDEN["epoch"], row_id=case["rowId"], board=case["board"],
                               delta=case["delta"], verification=expected["verification"])
        if _golden_text_is_stale(expected):
            for doc in (got, expected):
                for key in STALE_GOLDEN_TEXT:
                    doc["fullRun"].pop(key)
        assert got == expected, name


def test_the_golden_qubit_text_is_either_current_or_exactly_the_pre_swap_002_text():
    """The exemption above covers only the old text, never an arbitrary difference."""
    run = GOLDEN["cases"]["full_submission"]["panel"]["fullRun"]
    if _golden_text_is_stale(GOLDEN["cases"]["full_submission"]["panel"]):
        assert "32 w Toffoli" in run["qubitsRule"] and "8e37ce7" in run["qubitsRule"]
        assert run["qubitsLabel"].endswith("not Lean-evaluated on this policy)")
    else:
        assert (run["qubitsLabel"], run["qubitsRule"]) == (mapping.PEAK_LABEL, mapping.PEAK_RULE)


def test_the_peak_text_says_the_truth_about_the_negation_and_names_the_placeholder_pin():
    rule = mapping.peak_rule()
    for text in (rule, mapping.peak_rule(True), mapping.peak_label(), mapping.peak_label(True)):
        assert "32 w" not in text and "8e37ce7" not in text
    for fact in ("one-clean-ancilla increment", "`oneQubit`", "negation: \"incrementer\"", "ONE clean qubit", "12w - 28", "10w - 18",
                 "17w - 22", "17w - 5", "5w - 3", "5w + 1", "exact for w >= 7", mapping.PIN):
        assert fact in rule, fact
    # the placeholder until PR #79's merge commit exists; a one-line sed then fills in the 40-hex SHA and this still holds
    assert mapping.PIN == "eb00c5adc72832469a5f223fbec6c8b75745d2dd" or re.fullmatch(r"[0-9a-f]{40}", mapping.PIN)


def test_the_label_depends_on_the_per_row_lean_peak_flag_and_defaults_to_not_evaluated():
    assert (mapping.PEAK_LABEL, mapping.PEAK_RULE) == (mapping.peak_label(False), mapping.peak_rule(False))
    assert mapping.peak_label().endswith("not Lean-evaluated on this policy)")
    assert "Lean has not evaluated it on this policy" in mapping.peak_rule()
    assert "not Lean-evaluated" not in mapping.peak_label(True) and "Lean-evaluated on this policy)" in mapping.peak_label(True)
    assert "has not evaluated" not in mapping.peak_rule(True) and "kernel has evaluated" in mapping.peak_rule(True)
    case = GOLDEN["cases"]["full_submission"]
    kw = dict(epoch=GOLDEN["epoch"], row_id=case["rowId"], board=case["board"], delta=case["delta"], verification=case["panel"]["verification"])
    default = mapping.panel_of(case["view"], **kw)["fullRun"]
    assert (default["qubitsLabel"], default["qubitsRule"]) == (mapping.peak_label(False), mapping.peak_rule(False))
    flagged = mapping.panel_of(case["view"], lean_peak=True, **kw)["fullRun"]
    assert (flagged["qubitsLabel"], flagged["qubitsRule"]) == (mapping.peak_label(True), mapping.peak_rule(True))
    default.pop("qubitsLabel"), default.pop("qubitsRule"), flagged.pop("qubitsLabel"), flagged.pop("qubitsRule")
    assert default == flagged, "the flag changes the text and nothing else"


