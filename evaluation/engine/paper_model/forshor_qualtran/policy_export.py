"""L2Q policy -> ForShor policy intake: the way back from a planned `PhasePolicy` to a submission.

`policy.load_policy_submission` reads ForShor's `forshor.policy-submission/v1`; this module writes the
three things ForShor's intake needs for any policy L2Q plans:

* `submission_json(P)`     -- a `forshor.policy-submission/v1`-shaped document (bands with index,
                              threshold, k, points, ops), readable back by `load_policy_submission`;
* `policy_template_lean(P)` -- `Submission/PolicyTemplate.lean`, the file a policy submitter owns: one
                              `ShorLoweringSetup` per band with C1-C4 closed by `decide +kernel`, and the
                              `ShorPolicySubmission` (same text `k_sequence_DP_planner/make_policy_template.py`
                              emits, generated from the tables themselves);
* `policy_check_lean(P, stock)` -- `Submission/PolicyCheck.lean` re-targeted at P's thresholds. ForShor's
                              stock file hard-codes its sample policy (`[(40, band0), (14, band1)]`,
                              `choose 39`, ...), so any other policy fails the build until that file is
                              edited; this rewrites exactly its policy-specific lines (band list, per-band
                              k/ops identities, `choose` at every band edge, `bandShrinks` per band) and
                              drops the stock-only threshold-12 example. Reported to ForShor as a gap.

The submission JSON is L2Q's export, not ForShor output: `ir` is null and `ir_status` says who wrote it.
ForShor's own `forshor_policy_submission` (after `lake build PolicySubmission`) is the authoritative
document, and its bands must equal this one's -- `tests/test_policy_export.py` checks that against the
kernel-checked n = 2048 intake in `artifacts/lean_policy/dp2048/`.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List, Optional

from .policy import POLICY_SUBMISSION_SCHEMA, PhasePolicy, ToomCookTable


def _points_json(T: ToomCookTable) -> List[Dict[str, Any]]:
    return [{"kind": "int", "z": v} if kd == "int" else {"kind": "frac", "m": v} for kd, v in T.points]


def submission_json(P: PhasePolicy, *, n: Optional[int] = None, note: str = "") -> Dict[str, Any]:
    P.check()
    return {
        "schema": POLICY_SUBMISSION_SCHEMA,
        "name": P.name,
        "bands": [{"index": i, "threshold": int(b.threshold), "k": b.table.k, "points": _points_json(b.table),
                   "ops": b.table.ops, "table_name": b.table.name} for i, b in enumerate(P.bands)],
        "ir": None,
        "ir_status": "EXPORTED BY Lean-To-Qualtran (forshor_qualtran.policy_export), not by ForShor's "
                     "forshor_policy_submission; admissibility is ForShor's intake (lake build PolicySubmission).",
        "leaf": (f"widths below the last threshold use the schoolbook leaf; with these bands that is "
                 f"n < {P.bands[-1].threshold}" if P.bands else "every width uses the schoolbook leaf"),
        **({"benchmark": {"bits": int(n)}} if n else {}),
        **({"note": note} if note else {}),
    }


def _lean_op(o: Dict[str, Any]) -> str:
    t = o["op"]
    if t == "addScaled":
        return f"valid_ops.addScaled {o['dst']} {o['src']} {'true' if o['negSrc'] else 'false'} {o['shift']}"
    if t == "phaseProduct" or t == "negate":
        return f"valid_ops.{t} {o['i']}"
    if t in ("shiftL", "shiftR"):
        return f"valid_ops.{t} {o['i']} {o['n']}"
    raise ValueError(t)


def policy_template_lean(P: PhasePolicy, *, generator: str = "forshor_qualtran.policy_export") -> str:
    P.check()
    if not P.bands:
        raise ValueError("an empty policy has no ShorPolicySubmission (ForShor needs at least one band)")
    s = ["import FastMultiplication.ShorVerification.Framework.ToomCookTable",
         "import FastMultiplication.ShorVerification.Framework.Policy",
         "import FastMultiplication.ShorVerification.Submission.Decide", "",
         f"/-! Generated by {generator} from L2Q-planned tables. -/", "",
         "namespace PolicySubmission", "", "open Shor Operations", ""]
    for i, b in enumerate(P.bands):
        T = b.table
        s += [f"/-! band {i}: threshold {b.threshold}, table `{T.name}` -/", "",
              f"abbrev band{i}K : ℕ := {T.k}", "",
              f"def band{i}Pts : List Point :=",
              "  [" + "\n  , ".join(f"Point.{kd} ({v})" for kd, v in T.points) + "]", "",
              f"def band{i}Ops : Prog band{i}K :=",
              "  [ " + "\n  , ".join(_lean_op(o) for o in T.ops) + "\n  ]", "",
              f"theorem band{i}Hpts : band{i}Pts.length = q band{i}K := rfl", "",
              f"def band{i} : ShorLoweringSetup where",
              f"  k := band{i}K", "  hk := by decide", f"  pts := band{i}Pts", f"  hpts := band{i}Hpts",
              f"  good := goodToomCookPoints_of_distinct band{i}Hpts (by decide +kernel)",
              f"  ops := band{i}Ops", "  consumes := by decide +kernel", "  returns := by decide +kernel", ""]
    s += ["def policy : ShorPolicySubmission where",
          "  bands := [" + ", ".join(f"({b.threshold}, band{i})" for i, b in enumerate(P.bands)) + "]",
          "  sorted := by decide", "", "end PolicySubmission", ""]
    return "\n".join(s)


def band_shrinks(P: PhasePolicy, i: int) -> bool:
    """`Shor.Policy.bandShrinks P i` (`Submission/PolicyDecide.lean`): does band ``i``'s table shrink the
    operand width at every width the band covers? The top band covers its threshold alone; band ``i``
    covers ``[t_i, t_{i-1})``. ``False`` is ForShor's performance advisory, never an admissibility failure."""
    b = P.bands[i]
    ws = [b.threshold] if i == 0 else range(b.threshold, P.bands[i - 1].threshold)
    return all(b.table.next_width(w, w) < w for w in ws)


def policy_check_lean(P: PhasePolicy, stock: str, *, top: Optional[int] = None) -> str:
    """ForShor's stock `PolicyCheck.lean` with its policy-specific lines rewritten for `P`."""
    P.check()
    bands = list(P.bands)
    ts = [b.threshold for b in bands]
    top = max(int(top or 0), ts[0])
    lines = stock.split("\n")

    def find(pred) -> List[int]:
        return [i for i, l in enumerate(lines) if pred(l)]

    def replace_block(idx: List[int], new: List[str]) -> None:
        if not idx:
            raise ValueError("stock PolicyCheck.lean has changed shape; cannot re-target it")
        lo, hi = idx[0], idx[-1]
        if idx != list(range(lo, hi + 1)):
            raise ValueError(f"stock PolicyCheck.lean: lines {idx} are not contiguous")
        lines[lo:hi + 1] = new

    bl = f"example : policy.bands = [{', '.join(f'({t}, band{i})' for i, t in enumerate(ts))}] := rfl"
    ident = [l for i in range(len(bands)) for l in (f"example : band{i}.k = band{i}K := rfl",
                                                     f"example : band{i}.ops = band{i}Ops := rfl")]
    replace_block(find(lambda l: l.startswith("example : policy.bands =") or re.match(r"example : band\d+\.(k|ops) =", l)),
                  [bl] + ident)
    ch = [f"example : policy.policy.choose {top} = some band0.table := rfl"]
    for i, t in enumerate(ts):
        ch.append(f"example : policy.policy.choose {t} = some band{i}.table := rfl")
        ch.append(f"example : policy.policy.choose {t - 1} = "
                  + (f"some band{i + 1}.table := rfl" if i + 1 < len(ts) else "none := rfl"))
    if ts[-1] == 0:
        ch.pop()                                   # nothing below threshold 0
    ch = list(dict.fromkeys(ch))
    replace_block(find(lambda l: l.startswith("example : policy.policy.choose")), ch)
    shrink_lines = find(lambda l: l.startswith("example : Shor.Policy.bandShrinks policy.policy"))
    if shrink_lines:                               # ForShor's stock check; the L2Q fork drops them (RT-1)
        replace_block(shrink_lines,
                      [f"example : Shor.Policy.bandShrinks policy.policy {i} = "
                       f"{'true' if band_shrinks(P, i) else 'false'} := by decide +kernel"
                       for i in range(len(bands))])
    text = "\n".join(lines)
    # the stock "check has teeth" example is about the sample policy's own band 1 at threshold 12
    text = re.sub(r"/-- And the check has teeth:.*?= false := by decide \+kernel\n\n", "", text, flags=re.S)
    return text
