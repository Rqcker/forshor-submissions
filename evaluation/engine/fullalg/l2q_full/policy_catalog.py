"""The ForShor table catalog: one Lean module per table, validated once; policies assembled from it.

Generates, inside a ForShor checkout (the L2Q fork, `Submission/Catalog/Basic.lean`):

* `Submission/Catalog/Tables/<ident>.lean` per table: the `ShorLoweringSetup` with C1-C4 closed by
  `decide +kernel` (the same text as a band of `policy_export.policy_template_lean`), `#assert_axioms` on
  it, and `extract_catalog_table` (its band bodies, extracted once). Lake builds each module once and
  caches it, so a table is never re-checked or re-extracted for another policy.
* `Submission/Catalog/Common.lean`: the policy-independent `qft` / `shor_gate` / `shor` templates.
* `Submission/Catalog/All.lean`: every table, by name, for `forshor_policy_submission catalog ...`.

A policy is then a runtime argument, `THRESHOLD:TABLE,...`, to the executable; no Lean is rebuilt.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, Iterable, List

from .policy import ToomCookTable, table_sha256
from .policy_export import _lean_op

SUB = Path("FastMultiplication") / "ShorVerification" / "Submission"
MOD = "FastMultiplication.ShorVerification.Submission.Catalog"


def lean_ident(name: str) -> str:
    """A Lean identifier for a catalog table name (`planA-sequential-k5` -> `T_planA_sequential_k5`)."""
    return "T_" + re.sub(r"[^A-Za-z0-9]", "_", name)


def table_module(T: ToomCookTable) -> str:
    ident = lean_ident(T.name)
    return "\n".join([
        f"import {MOD}.Basic",
        "import FastMultiplication.ShorVerification.Submission.Audit", "",
        f"/-! Catalog table `{T.name}` (k = {T.k}; table sha256 `{table_sha256(T)}`).",
        "Generated by forshor_qualtran.policy_catalog. C1-C4 are closed by the kernel; the band bodies are",
        "extracted once; Lake builds this module once for every policy that uses the table. -/", "",
        f"namespace Shor.Catalog.Tables.{ident}", "", "open Shor Operations", "",
        f"abbrev K : ℕ := {T.k}", "",
        "def pts : List Point :=",
        "  [" + "\n  , ".join(f"Point.{kd} ({v})" for kd, v in T.points) + "]", "",
        "def ops : Prog K :=",
        "  [ " + "\n  , ".join(_lean_op(o) for o in T.ops) + "\n  ]", "",
        "theorem hpts : pts.length = q K := rfl", "",
        # large tables' `decide +kernel` C1-C4 exceed the default heartbeats (k = 14..16 measured); only
        # k >= 7 gets the option, so the text (and Lake's cache) of every smaller table is unchanged
        *(["set_option maxHeartbeats 0 in"] if T.k >= 7 else []),
        "def setup : ShorLoweringSetup where",
        "  k := K", "  hk := by decide", "  pts := pts", "  hpts := hpts",
        "  good := goodToomCookPoints_of_distinct hpts (by decide +kernel)",
        "  ops := ops", "  consumes := by decide +kernel", "  returns := by decide +kernel", "",
        "#assert_axioms setup", "",
        "set_option maxHeartbeats 0 in",
        f'extract_catalog_table table "{T.name}" setup', "",
        f"end Shor.Catalog.Tables.{ident}", ""])


def common_module() -> str:
    return "\n".join([
        f"import {MOD}.Basic",
        "import FastMultiplication.ShorVerification.Implementation.Reference.StandardLoweringSetup", "",
        "/-! The policy-independent templates (`qft`, `shor_gate`, `shor`), extracted once. They reach the",
        "bands only through the dispatcher's name, so the setup they are extracted against is immaterial;",
        "L2Q's read-back checks them byte-equal across every policy it has seen. -/", "",
        "namespace Shor.Catalog", "",
        "def commonSetup : ShorLoweringSetup := Shor.standardLoweringSetup 2 (by decide)", "",
        "extract_catalog_common common commonSetup", "",
        "end Shor.Catalog", ""])


def all_module(tables: Iterable[ToomCookTable]) -> str:
    ts = sorted(tables, key=lambda t: t.name)
    return "\n".join(
        [f"import {MOD}.Common"] + [f"import {MOD}.Tables.{lean_ident(t.name)}" for t in ts] + ["",
         "/-! Every catalog table, by name. Generated by forshor_qualtran.policy_catalog. -/", "",
         "namespace Shor.Catalog", "",
         "def tables : List CatalogTable :=",
         "  [ " + "\n  , ".join(f"Tables.{lean_ident(t.name)}.table" for t in ts) + "\n  ]", "",
         "end Shor.Catalog", ""])


def write_catalog(forshor: Path, tables: Iterable[ToomCookTable]) -> Dict[str, str]:
    """Write the catalog modules into ``forshor``; returns ``{table name: module}``. Only changed files are
    rewritten, so Lake's cache stays valid for every table that did not change."""
    tables = list(tables)
    names = [t.name for t in tables]
    if len(set(names)) != len(names):
        raise ValueError("duplicate table names in the catalog")
    root = forshor / SUB / "Catalog"
    (root / "Tables").mkdir(parents=True, exist_ok=True)

    def put(path: Path, text: str):
        if not path.is_file() or path.read_text() != text:
            path.write_text(text)

    out = {}
    for T in tables:
        put(root / "Tables" / f"{lean_ident(T.name)}.lean", table_module(T))
        out[T.name] = f"{MOD}.Tables.{lean_ident(T.name)}"
    put(root / "Common.lean", common_module())
    put(root / "All.lean", all_module(tables))
    return out
