#!/usr/bin/env python3
"""A site policy as a submission file, `TableGeneration/Submission/Policy.lean` (ForShor's `PolicyTemplate` format for PhaseProduct, its `PTPPolicyTemplate` format for PhaseTripleProduct): put a library-optimized policy through Lean (PLAN_v2 L1).

    python harness/policy_to_template.py policy.json > Policy.lean
    python harness/policy_to_template.py policy.json --forshor /path/to/ForShor > Policy.lean
    python harness/policy_to_template.py policy.json --lib ForShor > Policy.lean

ForShor's Lean library is `ForShor` (it was `FastMultiplication` before ForShor bb2aae0; at the pinned commit `21e129a` there is only
`ForShor`). `--forshor` checks the name against a ForShor checkout (`library_of`). The file goes to
`ForShor/ShorVerification/Submission/PolicyTemplate.lean` (`template_rel`).

`policy.json` is any policy the site reads (tcost format, `{"policy": ...}`, an archived operations.json with a recursion
policy). The output follows the shipped template exactly: per distinct table an arity, a point list, a program, C1, and the
`ShorLoweringSetup` record with C1 to C4 closed by `decide +kernel`; then `policy` with the bands widest first and
`sorted := by decide`. Nothing in the generated file is trusted: `forshor_verify.py` runs it through ForShor's own checks.

What a ForShor policy can and cannot say, so the converter refuses rather than approximates:
  * PhaseProduct only (the order-finding circuit has no triple product);
  * 1 < k <= 8 (the submission's contract);
  * thresholds strictly decreasing (tcost enforces it too);
  * `"negation"` (optional, on the policy object): `"oneQubit"` (ForShor's default) or `"scratch"` (`Shor.NegationMethod`, a
    qubit against T-count choice, swap-002). Absent or `"oneQubit"` writes exactly the template it wrote before the key existed
    (ForShor's `ShorPolicySubmission.negation` defaults to `.oneQubit`, so no line is needed); `"scratch"` adds one
    line, `negation := .scratch`, to the `policy` record. Any other value is an error (exit code 2). Needs a ForShor
    checkout that has `NegationMethod` (PR #79, eb00c5a); UNTESTED against Lean here.
  * a policy re-optimised per width (a decision map: a different table at each width, per phase-product site) cannot be
    written as bands, so it is not a ForShor submission.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "engine"))

import site_engine  # noqa: E402,F401
from tcost import tables as tt  # noqa: E402

MAX_K = 8


class TemplateError(ValueError):
    pass


class NegationError(TemplateError):
    """The policy's optional `"negation"` key is not `"oneQubit"` or `"scratch"` (the command line exits with 2)."""


#: ForShor `Shor.NegationMethod` (Framework/NegationMethod.lean); `oneQubit` is the `ShorPolicySubmission` default.
NEGATIONS = ("oneQubit", "scratch")


def negation_of(policy: dict) -> "str | None":
    """The optional `"negation"` key of a policy dict: None when it is absent or names the default (`oneQubit`, which the
    template leaves to the record's default value), `"scratch"` otherwise. Anything else, null included, is an error."""
    if "negation" not in policy:
        return None
    v = policy["negation"]
    if not isinstance(v, str) or v not in NEGATIONS:
        raise NegationError(f'bad negation {v!r}: expected "oneQubit" (the default) or "scratch"')
    return None if v == "oneQubit" else v


def requested_negation(policy: dict) -> str:
    """The negation method the policy JSON asks for, as ForShor spells it: `"oneQubit"` when the key is absent (the default)."""
    return negation_of(policy) or "oneQubit"


def requested_negation_from_file(path: Path, index: int = 0) -> str:
    """`requested_negation` of policy `index` of the policy file `path` (the same object `template_from_file` reads)."""
    return requested_negation(tt.policy_docs(json.loads(Path(path).read_text()))[index])


#: ForShor's Lean library name: `ForShor` (`FastMultiplication` before bb2aae0, which the pinned commit does not have).
LIBS = ("ForShor",)
DEFAULT_LIB = "ForShor"
IMPORTS = ("ShorVerification.Framework.ToomCookTable", "ShorVerification.Framework.Policy",
           "ShorVerification.Submission.Decide")
HEADER_BODY = """
/-!
Generated by the ForShor Challenge starter pack's `harness/policy_to_template.py` from a site policy. Edit nothing by hand: the verifier decides.
-/

namespace PolicySubmission

open Shor Operations
"""


def _check_lib(lib: str) -> str:
    if lib not in LIBS:
        raise TemplateError(f"unknown ForShor library {lib!r}; expected one of {', '.join(LIBS)}")
    return lib


def header(lib: str = DEFAULT_LIB) -> str:
    """The template's three imports for ForShor library `lib`, then the fixed preamble."""
    _check_lib(lib)
    return "".join(f"import {lib}.{m}\n" for m in IMPORTS) + HEADER_BODY


#: The `main` header, kept under its old name for callers that import it.
HEADER = header(DEFAULT_LIB)


def template_rel(lib: str = DEFAULT_LIB) -> str:
    """Where the template lives in a ForShor checkout whose library is `lib`."""
    return f"{_check_lib(lib)}/ShorVerification/Submission/PolicyTemplate.lean"


def library_of(forshor: Path) -> str:
    """The Lean library name of the ForShor checkout at `forshor`: the one whose Submission directory exists."""
    found = [lib for lib in LIBS if (Path(forshor) / lib / "ShorVerification" / "Submission").is_dir()]
    if len(found) != 1:
        raise TemplateError(f"{forshor}: expected exactly one of {', '.join(f'{l}/ShorVerification/Submission' for l in LIBS)}, "
                            f"found {len(found)}")
    return found[0]


def _point(p: str) -> str:
    """tcost point spelling -> `Point.int z` / `Point.frac m` (frac 0 is infinity; frac m is the point 1/m)."""
    kind, v = tt.parse_point(p)
    z = int(v)
    if kind == "int":
        return f"Point.int ({z})" if z < 0 else f"Point.int {z}"
    return f"Point.frac ({z})" if z < 0 else f"Point.frac {z}"


def _op(o) -> str:
    kind = o[0]
    if kind == "phaseProduct":
        return f"valid_ops.phaseProduct {o[1]}"
    if kind == "negate":
        return f"valid_ops.negate {o[1]}"
    if kind in ("shiftL", "shiftR"):
        return f"valid_ops.{kind} {o[1]} {o[2]}"
    if kind == "addScaled":
        return f"valid_ops.addScaled {o[1]} {o[2]} {'true' if o[3] else 'false'} {o[4]}"
    raise TemplateError(f"unknown operation {o!r}")


def _table_block(j: int, T: tt.Table) -> str:
    pts = ", ".join(_point(tt.point_str(p)) for p in T.point_order)
    ops = "\n  , ".join(_op(o) for o in T.ops)
    return f"""
/-! ===== table {j} (k = {T.k}) ===== -/

abbrev t{j}K : ℕ := {T.k}

def t{j}Pts : List Point :=
  [{pts}]

def t{j}Ops : Prog t{j}K :=
  [ {ops}
  ]

theorem t{j}Hpts : t{j}Pts.length = q t{j}K := rfl

def t{j} : ShorLoweringSetup where
  k := t{j}K
  hk := by decide
  pts := t{j}Pts
  hpts := t{j}Hpts
  good := goodToomCookPoints_of_distinct t{j}Hpts (by decide +kernel)
  ops := t{j}Ops
  consumes := by decide +kernel
  returns := by decide +kernel
"""


PTP_IMPORTS = ("ShorVerification.Framework.ToomCookTable", "ShorVerification.Implementation.PhaseTripleProduct.Statement")
PTP_HEADER_BODY = """
/-!
Generated by the ForShor Challenge starter pack's `harness/policy_to_template.py` from a site policy. Edit nothing by hand: the verifier decides.
-/

namespace PTPPolicySubmission

open Shor Operations
"""


def _ptp_table_block(j: int, T: tt.Table) -> str:
    pts = ", ".join(_point(tt.point_str(p)) for p in T.point_order)
    ops = "\n  , ".join(_op(o) for o in T.ops)
    return f"""
/-! ===== table {j} (k = {T.k}) ===== -/

abbrev t{j}K : ℕ := {T.k}

def t{j}Pts : List Point :=
  [{pts}]

def t{j}Ops : Prog t{j}K :=
  [ {ops}
  ]

theorem t{j}Hpts : t{j}Pts.length = PTP.pointCount t{j}K := by decide

def tbl{j} : PTP.PTPTable := ⟨t{j}K, t{j}Pts, t{j}Ops⟩
"""


def ptp_template_text(P: tt.Policy, lib: str = DEFAULT_LIB, negation: "str | None" = None) -> str:
    """A PhaseTripleProduct site policy as ForShor's `PTPPolicyTemplate.lean` (the submission file `Policy.lean` for that board)."""
    negation = None if negation is None else negation_of({"negation": negation})
    if not P.bands:
        raise TemplateError("the policy has no bands")
    index: Dict[str, int] = {}
    tables: List[tt.Table] = []
    bands: List[Tuple[int, int]] = []
    last = None
    for b in P.bands:
        T = b.table
        if not 2 <= T.k <= MAX_K:
            raise TemplateError(f"a band has k = {T.k}; submissions take 1 < k <= {MAX_K}")
        if last is not None and not b.threshold < last:
            raise TemplateError("thresholds must strictly decrease, widest first")
        last = b.threshold
        if T.digest not in index:
            index[T.digest] = len(tables)
            tables.append(T)
        bands.append((int(b.threshold), index[T.digest]))
    out = ["".join(f"import {_check_lib(lib)}.{m}\n" for m in PTP_IMPORTS) + PTP_HEADER_BODY]
    out += [_ptp_table_block(j, T) for j, T in enumerate(tables)]
    pairs = ", ".join(f"⟨{t}, tbl{j}⟩" for t, j in bands)
    neg_line = "  negation := .scratch\n" if negation else ""
    out.append(f"""
/-! ===== the policy ===== -/

def policy : PTP.PTPPolicy where
  bands := [{pairs}]
{neg_line}
end PTPPolicySubmission
""")
    return "".join(out)


def template_text(P: tt.Policy, lib: str = DEFAULT_LIB, negation: "str | None" = None) -> str:
    """`negation`: None or `"oneQubit"` (the default; no line is written) or `"scratch"` (`negation := .scratch`)."""
    negation = None if negation is None else negation_of({"negation": negation})
    if P.mode == tt.TRIPLE:
        return ptp_template_text(P, lib, negation)
    if P.mode != tt.PAIR:
        raise TemplateError(f"unknown policy mode {P.mode!r}")
    if not P.bands:
        raise TemplateError("the policy has no bands")
    index: Dict[str, int] = {}
    tables: List[tt.Table] = []
    bands: List[Tuple[int, int]] = []
    last = None
    for b in P.bands:
        T = b.table
        if not 2 <= T.k <= MAX_K:
            raise TemplateError(f"a band has k = {T.k}; ForShor policies take 1 < k <= {MAX_K}")
        if last is not None and not b.threshold < last:
            raise TemplateError("thresholds must strictly decrease, widest first")
        last = b.threshold
        if T.digest not in index:
            index[T.digest] = len(tables)
            tables.append(T)
        bands.append((int(b.threshold), index[T.digest]))
    out = [header(lib)]
    out += [_table_block(j, T) for j, T in enumerate(tables)]
    pairs = ", ".join(f"({t}, t{j})" for t, j in bands)
    neg_line = "  negation := .scratch\n" if negation else ""
    out.append(f"""
/-! ===== the policy ===== -/

def policy : ShorPolicySubmission where
  bands := [{pairs}]
  sorted := by decide
{neg_line}
end PolicySubmission
""")
    return "".join(out)


def accepted_policies(docs) -> list:
    """`Policy.from_json` of each doc (each band's table is checked as it is read), refusing what the boards refuse: no policy, or a
    policy with no bands (Lean reads `[]` as "not entered"; `Policy.leaf` is the schoolbook baseline). Unlike the engine's
    `checked_policies` it allows different tables of the same k in different bands, as the boards and both Lean checks do."""
    pols = [tt.Policy.from_json(d) for d in docs]
    if not pols:
        raise tt.TableError("no policy in the document")
    for p in pols:
        if not p.bands:
            raise tt.TableError(f"{p.name or p.mode}: no bands (not entered); Policy.leaf is the schoolbook baseline")
    return pols


def template_from_file(path: Path, index: int = 0, lib: str = DEFAULT_LIB) -> str:
    """The template of policy `index` of the policy file `path`, with that policy object's own `"negation"` key honoured."""
    docs = tt.policy_docs(json.loads(Path(path).read_text()))
    pols = accepted_policies(docs)
    return template_text(pols[index], lib, negation_of(docs[index]))


def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("policy", type=Path)
    ap.add_argument("--index", type=int, default=0, help="which policy of a file that holds several")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--lib", choices=LIBS, help=f"ForShor's library name (default {DEFAULT_LIB}, the only one at the pinned commit)")
    g.add_argument("--forshor", type=Path, help="a ForShor checkout; its library name is read off the tree")
    a = ap.parse_args(argv)
    try:
        lib = library_of(a.forshor) if a.forshor else (a.lib or DEFAULT_LIB)
        text = template_from_file(a.policy, a.index, lib)
    except NegationError as e:
        print(f"cannot write a ForShor policy: {e}", file=sys.stderr)
        return 2
    except TemplateError as e:
        print(f"cannot write a ForShor policy: {e}", file=sys.stderr)
        return 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
